namespace RouteGo.Fleet.Api.Features.Trips.ReplaceSchedule;

/// <summary>The schedule's new details, all given again: a bus on a route, departing at a time of day on chosen days, with a fare for every seat class.</summary>
public sealed class ReplaceScheduleRequest
{
    /// <summary>One of the operator's routes; a route other than the schedule's current one must be active.</summary>
    public Guid? RouteId { get; init; }

    /// <summary>One of the operator's active buses.</summary>
    public Guid? BusId { get; init; }

    /// <summary>Departure time of day from the source, HH:mm on the 24-hour clock, in IST.</summary>
    public string? DepartureTime { get; init; }

    /// <summary>1 to 7 different days of the week.</summary>
    public IReadOnlyList<DayOfWeek>? DaysOfWeek { get; init; }

    /// <summary>Exactly one fare for every seat class of the bus.</summary>
    public IReadOnlyList<ClassFareInput>? ClassFares { get; init; }
}

/// <summary>What a seat of one seat class costs.</summary>
public sealed class ClassFareInput
{
    /// <summary>One of the bus's seat classes, matched ignoring case.</summary>
    public string? SeatClass { get; init; }

    /// <summary>Whole Indian rupees (INR), 50 to 10,000. Sent as a number so a fraction can be refused by name.</summary>
    public decimal? Fare { get; init; }
}

/// <summary>What a seat of one seat class costs on the schedule's trips.</summary>
/// <param name="SeatClass">The seat class, spelt as the bus spells it.</param>
/// <param name="Fare">Whole Indian rupees (INR).</param>
public sealed record ClassFare(string SeatClass, int Fare);

/// <summary>The schedule as replaced.</summary>
public sealed class Schedule
{
    public required Guid ScheduleId { get; init; }

    public required string OperatorId { get; init; }

    public required Guid RouteId { get; init; }

    public required Guid BusId { get; init; }

    /// <summary>HH:mm in IST.</summary>
    public required string DepartureTime { get; init; }

    /// <summary>The days of service, Monday first.</summary>
    public required IReadOnlyList<DayOfWeek> DaysOfWeek { get; init; }

    /// <summary>One fare for every seat class of the bus, in the bus's seat-class order.</summary>
    public required IReadOnlyList<ClassFare> ClassFares { get; init; }

    public required ScheduleStatus Status { get; init; }

    /// <summary>The last service date (IST) up to which trips have been generated; a replacement never moves it.</summary>
    public required DateOnly TripsGeneratedThrough { get; init; }

    public required DateTimeOffset CreatedAt { get; init; }

    public required DateTimeOffset UpdatedAt { get; init; }
}

/// <summary>The replaced schedule and how its trips changed.</summary>
public sealed class ReplaceScheduleResponse
{
    public required Schedule Schedule { get; init; }

    /// <summary>Trips generated by this request.</summary>
    public required int CreatedTripCount { get; init; }

    /// <summary>Trips cancelled by this request.</summary>
    public required int CancelledTripCount { get; init; }

    /// <summary>Trips whose fares this request changed.</summary>
    public required int RepricedTripCount { get; init; }
}

public enum ReplaceScheduleOutcome
{
    Replaced,
    OperatorProfileNotReady,
    NotFound,
    ScheduleInactive,
    UnknownBus,
    UnknownRoute,
    BusInactive,
    RouteInactive,
    ClassFaresMismatch,
    BusTripOverlap,
}

/// <summary>How the replacement ended.</summary>
public sealed class ReplaceScheduleResult
{
    public required ReplaceScheduleOutcome Outcome { get; init; }

    /// <summary>The schedule and its trip counts when replaced.</summary>
    public ReplaceScheduleResponse? Response { get; init; }

    /// <summary>The bus's seat classes the fares left out, when the fares did not match them.</summary>
    public IReadOnlyList<string> MissingClasses { get; init; } = Array.Empty<string>();

    /// <summary>The fares' classes the bus does not have, when the fares did not match them.</summary>
    public IReadOnlyList<string> UnknownClasses { get; init; } = Array.Empty<string>();

    /// <summary>Every generated trip that would have overlapped another trip of the bus.</summary>
    public IReadOnlyList<TripConflict> Conflicts { get; init; } = Array.Empty<TripConflict>();
}

/// <summary>Which schedule to replace, for whom, and under which correlation ID its events are recorded.</summary>
/// <param name="ScheduleId">The schedule.</param>
/// <param name="OperatorId">The calling operator; only its schedules can be replaced.</param>
/// <param name="CorrelationId">The request's correlation ID, copied into every event.</param>
public sealed record ScheduleTarget(Guid ScheduleId, string OperatorId, string CorrelationId);

[ApiController]
[ApiExplorerSettings(GroupName = "Trips")]
[Route("schedules")]
public sealed class ReplaceScheduleController : ControllerBase
{
    private readonly ReplaceScheduleHandler _handler;
    private readonly ReplaceScheduleValidator _validator = new ReplaceScheduleValidator();

    public ReplaceScheduleController(IWriterConnectionFactory writerFactory, IClock clock)
    {
        _handler = new ReplaceScheduleHandler(writerFactory, clock);
    }

    /// <summary>Replace a schedule's details and rewrite its future trips (Operator only).</summary>
    /// <remarks>
    /// Full replacement of an active schedule's route, bus, departure time, days and fares. Future
    /// trips whose route, bus or departure time differ, or whose date is no longer a day of service,
    /// are cancelled (TripCancelled, reason "Schedule changed"); new trips are generated for days of
    /// service up to the generated-through date (TripScheduled); future trips differing only in fares
    /// are re-priced (FareChanged) unless they depart within 6 hours. All in one atomic step; refused
    /// whole with BUS_TRIP_OVERLAP on any overlap. Requires role Operator and the operator's Fleet
    /// profile. A schedule that belongs to another operator is reported as not found.
    /// </remarks>
    /// <param name="scheduleId">The schedule's identifier.</param>
    /// <param name="request">The schedule's new details.</param>
    /// <param name="cancellationToken">Cancels the replacement.</param>
    /// <response code="200">The schedule was replaced; the counts say how its trips changed.</response>
    /// <response code="400">A field failed validation (VALIDATION_FAILED, naming the field in errors).</response>
    /// <response code="401">No valid access token was presented (UNAUTHORIZED).</response>
    /// <response code="403">The caller is not an operator (FORBIDDEN), or its profile is not ready yet (OPERATOR_PROFILE_NOT_READY).</response>
    /// <response code="404">No schedule with this identifier belongs to the caller (NOT_FOUND).</response>
    /// <response code="409">The schedule is inactive (SCHEDULE_INACTIVE), or a resulting trip would overlap another trip of the bus (BUS_TRIP_OVERLAP, with conflicts).</response>
    /// <response code="422">The bus or route is unknown or inactive (UNKNOWN_BUS, UNKNOWN_ROUTE, BUS_INACTIVE, ROUTE_INACTIVE), or the fares do not match the bus's seat classes (CLASS_FARES_MISMATCH).</response>
    [Authorize(Policy = Policies.Operator)]
    [HttpPut("{scheduleId}")]
    [ProducesResponseType(typeof(ReplaceScheduleResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ValidationProblemDetails), StatusCodes.Status400BadRequest)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status403Forbidden)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status404NotFound)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status409Conflict)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status422UnprocessableEntity)]
    public async Task<IActionResult> ReplaceScheduleAsync(
        Guid scheduleId, ReplaceScheduleRequest request, CancellationToken cancellationToken)
    {
        ValidationResult validation = await _validator.ValidateAsync(request, cancellationToken);
        if (!validation.IsValid)
        {
            return ValidationProblem(validation.ToModelState());
        }

        string operatorId = User.FindFirst(TokenClaims.OperatorId)!.Value;
        string correlationId = CorrelationIdMiddleware.GetCorrelationId(HttpContext);
        var target = new ScheduleTarget(scheduleId, operatorId, correlationId);
        ReplaceScheduleResult result = await _handler.HandleAsync(target, request, cancellationToken);
        return ToActionResult(target, request, result);
    }

    private IActionResult ToActionResult(ScheduleTarget target, ReplaceScheduleRequest request, ReplaceScheduleResult result)
    {
        Guid routeId = request.RouteId!.Value;
        Guid busId = request.BusId!.Value;
        switch (result.Outcome)
        {
            case ReplaceScheduleOutcome.Replaced:
                return Ok(result.Response);
            case ReplaceScheduleOutcome.OperatorProfileNotReady:
                return ProblemResult.OperatorProfileNotReady(this, "Fleet has not yet created your operator profile.");
            case ReplaceScheduleOutcome.NotFound:
                return ProblemResult.NotFound(this, $"You have no schedule {target.ScheduleId}.");
            case ReplaceScheduleOutcome.ScheduleInactive:
                return ProblemResult.ScheduleInactive(this, $"Schedule {target.ScheduleId} is inactive; activate it before editing it.");
            case ReplaceScheduleOutcome.UnknownBus:
                return ProblemResult.UnknownBus(this, $"You have no bus {busId}.", busId);
            case ReplaceScheduleOutcome.UnknownRoute:
                return ProblemResult.UnknownRoute(this, $"You have no route {routeId}.", routeId);
            case ReplaceScheduleOutcome.BusInactive:
                return ProblemResult.BusInactive(this, $"Bus {busId} is inactive; activate it or choose another bus.", busId);
            case ReplaceScheduleOutcome.RouteInactive:
                return ProblemResult.RouteInactive(this, $"Route {routeId} is inactive; choose an active route.", routeId);
            case ReplaceScheduleOutcome.ClassFaresMismatch:
                return ProblemResult.ClassFaresMismatch(this, "The fares must name exactly the bus's seat classes.",
                    result.MissingClasses, result.UnknownClasses);
            case ReplaceScheduleOutcome.BusTripOverlap:
                return ProblemResult.BusTripOverlap(this,
                    $"{result.Conflicts.Count} of the schedule's trips would overlap another trip of the bus.", result.Conflicts);
            default:
                throw new InvalidOperationException($"Unhandled outcome '{result.Outcome}'.");
        }
    }
}
