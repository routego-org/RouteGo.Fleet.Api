namespace RouteGo.Fleet.Api.Features.Trips.DeactivateSchedule;

/// <summary>What a seat of one seat class costs on the schedule's trips.</summary>
/// <param name="SeatClass">The seat class, spelt as the bus spells it.</param>
/// <param name="Fare">Whole Indian rupees (INR).</param>
public sealed record ClassFare(string SeatClass, int Fare);

/// <summary>The schedule, inactive.</summary>
public sealed class Schedule
{
    public required Guid ScheduleId { get; init; }

    public required string OperatorId { get; init; }

    public required Guid RouteId { get; init; }

    public required Guid BusId { get; init; }

    /// <summary>HH:mm in IST.</summary>
    public required string DepartureTime { get; init; }

    /// <summary>The days of service, Monday first.</summary>
    public required IReadOnlyList<DayOfWeek> DaysOfWeek { get; init; }

    /// <summary>One fare per seat class, in the bus's seat-class order.</summary>
    public required IReadOnlyList<ClassFare> ClassFares { get; init; }

    public required ScheduleStatus Status { get; init; }

    /// <summary>The last service date (IST) up to which trips have been generated.</summary>
    public required DateOnly TripsGeneratedThrough { get; init; }

    public required DateTimeOffset CreatedAt { get; init; }

    public required DateTimeOffset UpdatedAt { get; init; }
}

/// <summary>The schedule and how its trips changed: deactivation only ever cancels.</summary>
public sealed class DeactivateScheduleResponse
{
    public required Schedule Schedule { get; init; }

    /// <summary>Trips generated by this request: always 0.</summary>
    public required int CreatedTripCount { get; init; }

    /// <summary>Future trips this request cancelled.</summary>
    public required int CancelledTripCount { get; init; }

    /// <summary>Trips whose fares this request changed: always 0.</summary>
    public required int RepricedTripCount { get; init; }
}

public enum DeactivateScheduleOutcome
{
    Deactivated,
    OperatorProfileNotReady,
    NotFound,
}

/// <summary>How the deactivation ended, with the change when the schedule was found.</summary>
/// <param name="Outcome">How the deactivation ended.</param>
/// <param name="Response">The schedule and its cancelled-trip count when found.</param>
public sealed record DeactivateScheduleResult(DeactivateScheduleOutcome Outcome, DeactivateScheduleResponse? Response = null);

[ApiController]
[ApiExplorerSettings(GroupName = "Trips")]
[Route("schedules")]
public sealed class DeactivateScheduleController : ControllerBase
{
    private readonly DeactivateScheduleHandler _handler;

    public DeactivateScheduleController(IWriterConnectionFactory writerFactory, IClock clock)
    {
        _handler = new DeactivateScheduleHandler(writerFactory, clock);
    }

    /// <summary>Stop a schedule and cancel its future trips (Operator only).</summary>
    /// <remarks>
    /// Makes the schedule inactive and cancels every future trip of it (TripCancelled, reason
    /// "Schedule deactivated"), all in one atomic step. Departed and cancelled trips are unchanged.
    /// Deactivating an inactive schedule changes nothing. Requires role Operator and the operator's
    /// Fleet profile. A schedule that belongs to another operator is reported as not found.
    /// </remarks>
    /// <param name="scheduleId">The schedule's identifier.</param>
    /// <param name="cancellationToken">Cancels the deactivation.</param>
    /// <response code="200">The schedule is inactive; the counts say how many trips were cancelled.</response>
    /// <response code="401">No valid access token was presented (UNAUTHORIZED).</response>
    /// <response code="403">The caller is not an operator (FORBIDDEN), or its profile is not ready yet (OPERATOR_PROFILE_NOT_READY).</response>
    /// <response code="404">No schedule with this identifier belongs to the caller (NOT_FOUND).</response>
    [Authorize(Policy = Policies.Operator)]
    [HttpPost("{scheduleId}/deactivate")]
    [ProducesResponseType(typeof(DeactivateScheduleResponse), StatusCodes.Status200OK)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status401Unauthorized)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status403Forbidden)]
    [ProducesResponseType(typeof(ProblemDetails), StatusCodes.Status404NotFound)]
    public async Task<IActionResult> DeactivateScheduleAsync(Guid scheduleId, CancellationToken cancellationToken)
    {
        string operatorId = User.FindFirst(TokenClaims.OperatorId)!.Value;
        string correlationId = CorrelationIdMiddleware.GetCorrelationId(HttpContext);
        var target = new ScheduleTarget(scheduleId, operatorId, correlationId);
        DeactivateScheduleResult result = await _handler.HandleAsync(target, cancellationToken);
        switch (result.Outcome)
        {
            case DeactivateScheduleOutcome.Deactivated:
                return Ok(result.Response);
            case DeactivateScheduleOutcome.OperatorProfileNotReady:
                return ProblemResult.OperatorProfileNotReady(this, "Fleet has not yet created your operator profile.");
            case DeactivateScheduleOutcome.NotFound:
                return ProblemResult.NotFound(this, $"You have no schedule {scheduleId}.");
            default:
                throw new InvalidOperationException($"Unhandled outcome '{result.Outcome}'.");
        }
    }
}

/// <summary>Which schedule to deactivate, for whom, and under which correlation ID its events are recorded.</summary>
/// <param name="ScheduleId">The schedule.</param>
/// <param name="OperatorId">The calling operator; only its schedules can be deactivated.</param>
/// <param name="CorrelationId">The request's correlation ID, copied into every event.</param>
public sealed record ScheduleTarget(Guid ScheduleId, string OperatorId, string CorrelationId);
